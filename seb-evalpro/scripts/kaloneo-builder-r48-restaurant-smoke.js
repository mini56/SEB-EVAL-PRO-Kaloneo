'use strict';
const fs=require('node:fs');const path=require('node:path');const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const original=JSON.parse(fs.readFileSync(path.join(root,'source/kaltest/tests/planning-cantine/1.0.0/test.json'),'utf8'));
const demo=JSON.parse(fs.readFileSync(path.join(root,'r48-demo/planning-restaurant-builder-r48.json'),'utf8'));
assert.equal(original.id,'planning_cantine');
assert.equal(demo.id,'planning_cantine_r48_demo');
assert.equal(demo.title,original.title);
for(const field of ['scenario','instruction']) assert.equal(demo[field],original[field]);
assert.deepEqual(demo.questions,original.questions);
assert.deepEqual(demo.bilanContributions,original.bilanContributions);
const content=demo.presentation.builderContent;
assert.equal(content.length,4);
assert.deepEqual(content.map(x=>x.type),['table-grid','text','text','image']);
const cells=content[0].table.cells;
assert.equal(cells.length,3);
assert.equal(cells.flat().filter(x=>x.kind==='select').length,15);
const oldIds=original.presentation.planningGrid.rows.flatMap(r=>r.questionIds);
assert.deepEqual(cells.flat().filter(x=>x.kind==='select').map(x=>x.questionId),oldIds);
assert.ok(original.presentation.planningGrid.guide.every(v=>content[2].text.includes(v)));
assert.ok(original.presentation.planningGrid.dishList.every(v=>content[1].text.includes(v)));
assert.ok(original.presentation.planningGrid.dessertList.every(v=>content[1].text.includes(v)));
assert.ok(fs.existsSync(path.join(root,'source/imageqcm/r48-plateau-repas.png')));
assert.ok(fs.existsSync(path.join(root,'source/imageqcm/r48-cantine-cuisinieres.png')));
const core=fs.readFileSync(path.join(root,'../kaloneo/builder-core.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'../kaloneo/test-builder.js'),'utf8');
const runtime=fs.readFileSync(path.join(root,'source/js/kaltest-pilot2-runtime.js'),'utf8');
for(const js of [core,ui,runtime]) {require('node:vm').runInNewContext('new Function('+JSON.stringify(js)+')');}
assert.ok(ui.includes('table.layoutOnly=check.checked'));
assert.ok(ui.includes('block.backgroundImage=result.image.data'));
assert.ok(ui.includes('r48-demo-restaurant'));
assert.ok(fs.readFileSync(path.join(root,'../kaloneo/test-builder.html'),'utf8').includes('restaurant-r48-demo.js'));
assert.ok(fs.existsSync(path.join(root,'../kaloneo/restaurant-r48-demo.js')));
assert.ok(runtime.includes('!Array.isArray(test.presentation?.builderContent) && renderPlanning(test, host)'));
console.log('R48_RESTAURANT_BUILDER_CONTRACT: OK; 15 questions and original content preserved');
