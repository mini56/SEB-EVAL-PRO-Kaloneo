'use strict';

const fs = require('fs');
const path = require('path');

const sebRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(sebRoot, '..');

function fail(message){
  console.error('KALONÉO test builder: ' + message);
  process.exit(2);
}

function assetDataUri(relativePath){
  const file = path.join(sebRoot, 'source', relativePath);
  if(!fs.existsSync(file)) return relativePath;
  const ext = path.extname(file).toLowerCase();
  const mime = ext === '.png' ? 'image/png'
    : ext === '.jpg' || ext === '.jpeg' ? 'image/jpeg'
    : ext === '.svg' ? 'image/svg+xml'
    : 'application/octet-stream';
  return 'data:' + mime + ';base64,' + fs.readFileSync(file).toString('base64');
}

const sourceArg = process.argv[2];
const outputArg = process.argv[3];
const exerciseIndex = Number(process.argv[4] || 1);
const exerciseTotal = Number(process.argv[5] || 1);

if(!sourceArg || !outputArg) {
  fail('Usage: node scripts/kaloneo-build-test-page.js <test.json> <output.html> [index] [total]');
}

const sourcePath = path.resolve(repoRoot, sourceArg);
const outputPath = path.resolve(sebRoot, outputArg);
const themePath = path.join(sebRoot, 'source', 'kaloneo', 'kaloneo-theme.css');
const enginePath = path.join(sebRoot, 'source', 'kaloneo', 'kaloneo-page-engine.js');

for (const file of [sourcePath, themePath, enginePath]) {
  if(!fs.existsSync(file)) fail('fichier absent: ' + file);
}

const test = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

if(!test.id || !test.title || !Array.isArray(test.questions)) {
  fail('KALTEST invalide ou incomplet.');
}

const definition = {
  schemaVersion: 1,
  generatedFrom: path.relative(repoRoot, sourcePath).replace(/\\/g, '/'),
  id: 'test-' + test.id,
  pageType: 'test',
  typography: {
    pageTitle: 28,
    sectionTitle: 22,
    blockTitle: 18,
    body: 17,
    control: 16,
    secondary: 15,
    field: 17,
    minimumFunctional: 15
  },
  test: {
    id: test.id,
    version: test.version || '',
    title: test.title,
    progress: {
      index: Number.isFinite(exerciseIndex) && exerciseIndex > 0 ? exerciseIndex : 1,
      total: Number.isFinite(exerciseTotal) && exerciseTotal > 0 ? exerciseTotal : 1
    },
    scenario: test.scenario || '',
    instruction: test.instruction || '',
    scenarioIcon: assetDataUri('imageqcm/scenario.png'),
    instructionIcon: assetDataUri('imageqcm/avatar_transparant.png'),
    presentation: test.presentation || {},
    questions: test.questions.map((q, i) => ({
      id: q.id || ('q' + (i + 1)),
      prompt: q.prompt || '',
      response: q.response || { type:'text' },
      unitInput: q.unitInput === true,
      units: Array.isArray(q.units) ? q.units : []
    })),
    calculator: {
      enabled: !!(test.calculator && test.calculator.compatible === true && test.calculator.defaultEnabled !== false)
    }
  },
  navigation: {
    abandon: { id:'abandon', label:'Abandonner l’exercice' },
    next: { id:'next', label:'Suivant' }
  }
};

const theme = fs.readFileSync(themePath,'utf8');
const engine = fs.readFileSync(enginePath,'utf8');
const definitionScript = 'window.KALONEO_PAGE_DEFINITION = Object.freeze(' + JSON.stringify(definition, null, 2) + ');';

const html = `<!doctype html>
<!-- GENERATED BY KALONÉO TEST FACTORY — DO NOT EDIT DIRECTLY -->
<html lang="fr">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>KALONÉO — ${String(test.title).replace(/[<>]/g,'')}</title>
<style>
${theme}
</style>
</head>
<body>
<main id="kaloneo-page-root"></main>
<script>
${definitionScript}
</script>
<script>
${engine}
</script>
</body>
</html>
`;

fs.mkdirSync(path.dirname(outputPath), { recursive:true });
fs.writeFileSync(outputPath, html, 'utf8');

console.log('KALONÉO TEST FACTORY: OK');
console.log('SOURCE=' + definition.generatedFrom);
console.log('TEST_ID=' + test.id);
console.log('OUTPUT=' + path.relative(sebRoot, outputPath));
console.log('QUESTIONS=' + definition.test.questions.length);
console.log('CALCULATOR=' + definition.test.calculator.enabled);
