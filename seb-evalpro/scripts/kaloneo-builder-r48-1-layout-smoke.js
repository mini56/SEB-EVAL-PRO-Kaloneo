'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.join(__dirname,'..','..');
const core=require(path.join(base,'kaloneo','builder-core.js'));
const model=core.definitionToModel(JSON.parse(fs.readFileSync(path.join(base,'seb-evalpro','r48-demo','planning-restaurant-builder-r48.json'),'utf8')));
const questionSnapshot=JSON.stringify(model.sourceDefinition.questions);
const text=model.blocks.find(b=>b.type==='text'&&String(b.text).includes('Indications'));
assert.ok(text,'Restaurant indication block missing');
text.textAlign='left';text.lineHeight='1.5';
let rebuilt=core.modelToDefinition(model);
assert.equal(JSON.stringify(rebuilt.questions),questionSnapshot,'question changed');
let cell=rebuilt.presentation.builderContent.find(x=>x.type==='text'&&x.text.includes('Indications'));
assert.equal(cell.style.textAlign,'left');assert.equal(cell.style.lineHeight,'1.5');
let restored=core.definitionToModel(rebuilt);
let restoredText=restored.blocks.find(b=>b.type==='text'&&String(b.text).includes('Indications'));
assert.equal(restoredText.textAlign,'left');assert.equal(restoredText.lineHeight,'1.5');
const js=fs.readFileSync(path.join(base,'kaloneo','test-builder.js'),'utf8');
const css=fs.readFileSync(path.join(base,'kaloneo','test-builder.css'),'utf8');
const realCss=fs.readFileSync(path.join(base,'seb-evalpro','source','css','kaltest-pilot2.css'),'utf8');
const previewCss=fs.readFileSync(path.join(base,'kaloneo','test-preview.css'),'utf8');
assert.ok(js.includes('activeGridEditorColumn'),'missing column selector state');
assert.ok(js.includes('td.hidden=(i!==activeColumn)'),'missing per-column cell display');
assert.ok(css.includes('.cell-grid-editor td[hidden]{display:none!important;}'));
assert.ok(realCss.includes('.kaltest-builder-runtime-zone>.kaltest-builder-content-item:last-child{flex:1 1 auto'));
assert.ok(previewCss.includes('.kb-zone>.kb-block:last-child{flex:1 1 auto'));
assert.ok(fs.readFileSync(path.join(base,'kaloneo','test-preview.js'),'utf8').includes('node.style.lineHeight=String(block.lineHeight)'));
assert.ok(fs.readFileSync(path.join(base,'seb-evalpro','source','js','kaltest-pilot2-runtime.js'),'utf8').includes('node.style.lineHeight=String(style.lineHeight)'));
console.log('R48_1_BUILDER_LAYOUT_SMOKE: OK (grid 6-col editing, fill last block, alignment, line-height, answers preserved)');
